/**
 * Lab verifier.
 *
 * Reads the *desired state* from the lab definition and the *actual state* from
 * the session's sandbox, then reports each requirement independently.
 *
 * A session's sandbox is either a Kubernetes namespace, a workspace directory,
 * or (in principle) both; the requirement type decides which evidence it needs
 * and the reader supplies it. Nothing in this file branches on track or lab.
 *
 * Explicit non-goals:
 *   - It never looks at command history, shell buffers, or terminal output. A
 *     student who creates the Deployment from a manifest, from `kubectl create`,
 *     or from a script they wrote themselves all pass identically, because all
 *     three produce the same desired state. The same is true of a workflow file
 *     written in vi, with a heredoc, or generated by a script.
 *   - It never reveals the solution. Failure details describe *what is wrong
 *     with the observed state*, not what to type.
 *   - It never runs anything the lab author wrote. Requirements select from a
 *     closed vocabulary of handlers that ship with the platform, and the three
 *     handlers that execute anything run a fixed argv from
 *     `workspace/tasks.ts` — never a command line from lab.yaml.
 *
 * Verification is always scoped to one session, which is supplied by the caller
 * from the session record — never by the browser.
 */
